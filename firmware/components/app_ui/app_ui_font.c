/* app_ui_font.c — the two glyph tables (F11a.1, F11a.3; design 07 §7.1).
 *
 * SMALL 5x7 (0x20..0x7E): the Adafruit SSD1306 table, carried over
 * byte-for-byte from the reference's main/app_display_font.h (MIT — see
 * docs/reference/PROVENANCE.md). Five column bytes per glyph, LSB at the
 * top; the sixth column of the 6x8 cell is the gap.
 *
 * LARGE 12x24 (F11a.3): authored here for exactly one screen — six passkey
 * digits legible across a dark yard — and reused by every M5 page. The
 * forms are seven-segment because at 12x24 that is what maximises stroke
 * width (3 px here), and legibility at distance is the whole requirement;
 * '1' gets a flag and a foot so it cannot be mistaken for a bare stem.
 * Each glyph's bitmap is drawn above its bytes: review the picture, not
 * the hex. F11a.2's PNG harness pins them as goldens in CI.
 */

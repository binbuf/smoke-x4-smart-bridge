import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';
import 'package:smoke_bridge/data/ble/bridge_protocol.dart';

import 'support/codecs.dart' as gen;

/// Pins the hand-written V0 codec slice in `lib/` to the generated contract.
/// A protocol change must fail here rather than drift silently (T40/T47 replace
/// the slice with the packaged codec).
void main() {
  test('characteristic UUIDs and limits match the generated contract', () {
    expect(bleLiveCharacteristicUuid, gen.bleCharacteristicByName('live').uuid);
    expect(
      bleControlCharacteristicUuid,
      gen.bleCharacteristicByName('control').uuid,
    );
    expect(
      bleResultCharacteristicUuid,
      gen.bleCharacteristicByName('result').uuid,
    );
    expect(
      bleSyncCtrlCharacteristicUuid,
      gen.bleCharacteristicByName('sync_ctrl').uuid,
    );
    expect(
      bleSyncDataCharacteristicUuid,
      gen.bleCharacteristicByName('sync_data').uuid,
    );
    expect(bleProtocolMajor, gen.protocolMajor);
    expect(bleSeqNone, gen.seqNone);
    expect(bleTempDetached, gen.tempDetached);
    expect(bleTempInvalid, gen.tempInvalid);
  });

  test('set_time control encodes exactly like the generated codec', () {
    final body = encodeSetTimeBody(
      unixMs: 1761566400123,
      tzOffsetMin: -420,
    );
    expect(body.length, gen.ControlSetTimeBody.size);
    final decodedBody = gen.ControlSetTimeBody.decode(body);
    expect(decodedBody.unixMs, 1761566400123);
    expect(decodedBody.tzOffsetMin, -420);

    final control = BridgeControl(op: BridgeControlOp.setTime, opId: 7);
    final bytes = control.encode(body);
    final generated = gen.Control.decode(bytes);
    expect(generated.ver, gen.protocolMajor);
    expect(generated.op, gen.ControlOp.setTime.wire);
    expect(generated.opId, 7);
    expect(bytes.length, gen.Control.size + gen.ControlSetTimeBody.size);

    final reencoded = Uint8List.fromList(<int>[
      ...gen.Control(op: gen.ControlOp.setTime.wire, opId: 7).encode(),
      ...gen.ControlSetTimeBody(
        unixMs: 1761566400123,
        tzOffsetMin: -420,
      ).encode(),
    ]);
    expect(bytes, reencoded);
  });

  test('result decodes generated bytes and preserves the status branch', () {
    for (final status in gen.ResultStatus.values) {
      final bytes = gen.Result(
        op: gen.ControlOp.setTime.wire,
        opId: 42,
        status: status.wire,
        detail: 'clock out of range',
      ).encode();
      final result = BridgeResult.decode(bytes);
      expect(result.op, gen.ControlOp.setTime.wire);
      expect(result.opId, 42);
      expect(result.status.wire, status.wire);
      expect(result.detail, 'clock out of range');
    }
  });

  test('live decodes generated bytes including sentinels', () {
    final bytes = gen.Live(
      flags:
          gen.liveFlagSmokePaired |
          gen.liveFlagSmokeLive |
          gen.liveFlagClockValid |
          gen.liveFlagStorageOk,
      temp: const <int>[2250, 1652, gen.tempDetached, gen.tempInvalid],
      seq: 0xA1B2C3D4,
      billowsTargetF10: 2250,
      batteryPct: 87,
      rssiLora: -71,
      ageS: 12,
    ).encode();

    final live = BridgeLive.decode(bytes);
    expect(live.smokePaired, isTrue);
    expect(live.smokeLive, isTrue);
    expect(live.clockValid, isTrue);
    expect(live.storageOk, isTrue);
    expect(live.seq, 0xA1B2C3D4);
    expect(live.billowsTargetF10, 2250);
    expect(live.batteryPct, 87);
    expect(live.rssiLora, -71);
    expect(live.ageS, 12);
    expect(live.tempF(0), 225.0);
    expect(live.tempF(1), 165.2);
    expect(live.tempF(2), isNull);
    expect(live.tempF(3), isNull);
  });

  test('sync_ctrl round-trips through the generated codec', () {
    final request = BridgeSyncRequest(
      cmd: BridgeSyncCmd.read,
      direction: BridgeSyncDirection.backward,
      cursorSeq: 1235,
      maxRecords: 64,
    );
    final generated = gen.SyncCtrl.decode(request.encode());
    expect(generated.ver, gen.protocolMajor);
    expect(generated.cmd, gen.SyncCmd.read.wire);
    expect(generated.direction, gen.SyncDirection.backward.wire);
    expect(generated.cursorSeq, 1235);
    expect(generated.maxRecords, 64);

    final fromGenerated = BridgeSyncRequest.decode(
      gen.SyncCtrl(
        cmd: gen.SyncCmd.read.wire,
        direction: gen.SyncDirection.forward.wire,
        cursorSeq: 102,
        maxRecords: 32,
      ).encode(),
    );
    expect(fromGenerated.direction, BridgeSyncDirection.forward);
    expect(fromGenerated.cursorSeq, 102);
    expect(fromGenerated.maxRecords, 32);
  });

  test('sync stream assembler reads a generated START/RECORDS/END stream', () {
    final records = <gen.SampleRec>[
      gen.SampleRec(
        seq: 200,
        unixS: 1761566300,
        temp: const <int>[2250, 1652, gen.tempDetached, 800],
        flags: gen.recordFlagProbe1Attached | gen.recordFlagClockValid,
      ),
      gen.SampleRec(
        seq: 201,
        unixS: 1761566330,
        temp: const <int>[2260, 1650, gen.tempDetached, 802],
        flags: gen.recordFlagProbe1Attached | gen.recordFlagClockValid,
      ),
    ];
    final payload = BytesBuilder()
      ..add(
        gen.SyncStart(
          generation: 0xA1B2C3D4,
          minSeq: 100,
          maxSeq: 201,
          startSeq: 200,
          count: records.length,
          recordSize: gen.recordSize,
          status: gen.SyncStatus.ok.wire,
        ).encode(),
      );
    for (final record in records) {
      payload.add(record.encode());
    }
    payload.add(
      gen.SyncEnd(
        status: gen.SyncStatus.ok.wire,
        nextSeq: 202,
        minSeq: 100,
        maxSeq: 201,
      ).encode(),
    );
    final frames = _frame(payload.toBytes());

    final assembler = BridgeSyncAssembler();
    BridgeSyncStream? stream;
    for (final frame in frames) {
      // Split inside frames at odd offsets to exercise platform chunking.
      for (var offset = 0; offset < frame.length; offset += 7) {
        final end = (offset + 7).clamp(0, frame.length);
        final result = assembler.add(
          Uint8List.sublistView(frame, offset, end),
        );
        if (result != null) stream = result;
      }
    }

    expect(stream, isNotNull);
    expect(stream!.start.generation, 0xA1B2C3D4);
    expect(stream.records.map((record) => record.seq), <int>[200, 201]);
    expect(stream.records.first.tempF(0), 225.0);
    expect(stream.records.last.tempF(1), 165.0);
    expect(stream.end.nextSeq, 202);
  });
}

/// Frames a contiguous sync stream with the generated header, exactly like the
/// bridge does.
List<Uint8List> _frame(Uint8List stream) {
  const maxPayload = 240;
  final frames = <Uint8List>[];
  var frameSeq = 0;
  for (var offset = 0; offset < stream.length; offset += maxPayload) {
    final end = (offset + maxPayload).clamp(0, stream.length);
    final payload = Uint8List.sublistView(stream, offset, end);
    var flags = 0;
    if (offset == 0) flags |= gen.syncFrameFlagStart;
    if (end == stream.length) flags |= gen.syncFrameFlagEnd;
    final header = gen.SyncFrame(
      frameSeq: frameSeq,
      flags: flags,
      len: payload.length,
    ).encode();
    frames.add(
      Uint8List(header.length + payload.length)
        ..setRange(0, header.length, header)
        ..setRange(header.length, header.length + payload.length, payload),
    );
    frameSeq = (frameSeq + 1) & 0xFF;
  }
  return frames;
}
